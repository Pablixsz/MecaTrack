#!/usr/bin/env bash
# MecaTrack - quality metrics in one report: tests + coverage, lint, code security, dependencies.
#
#   ./scripts/quality_report.sh            # prints the summary and writes docs/quality-report.md
#
# Same tools and thresholds as the CI/CD "test" job (.github/workflows/ci-cd.yml).
# Tests need PostgreSQL: TEST_DATABASE_URL, or DATABASE_URL in backend/.env (database *_test).
# Exit code is non-zero when a gate fails.
set -uo pipefail
cd "$(dirname "$0")/.." || exit 1

ROOT="$PWD"
PY="$ROOT/backend/venv/bin/python"
BIN="$ROOT/backend/venv/bin"
OUT="$ROOT/docs/quality-report.md"
COVERAGE_MIN="${COVERAGE_MIN:-90}"
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT

[ -x "$PY" ] || { echo "backend/venv missing: python3 -m venv backend/venv && backend/venv/bin/pip install -r backend/requirements-dev.txt"; exit 1; }
EXCLUDE=./venv,./mutants,./tests,./migrations

cd backend || exit 1
echo "==> pytest + coverage";  "$PY" -m pytest -q -p no:warnings --cov --cov-report=json:"$TMP/coverage.json" \
                                 --junitxml="$TMP/junit.xml" > "$TMP/pytest.txt" 2>&1; PYTEST_RC=$?
echo "==> ruff";               "$BIN/ruff" check --output-format json . > "$TMP/ruff.json" 2>/dev/null; RUFF_RC=$?
echo "==> bandit";             "$BIN/bandit" -q -r . -x "$EXCLUDE" -f json -o "$TMP/bandit.json" 2>/dev/null
                               "$BIN/bandit" -q -r . -x "$EXCLUDE" --severity-level medium > /dev/null 2>&1; BANDIT_RC=$?
echo "==> pip-audit";          "$BIN/pip-audit" -r requirements.txt -f json --progress-spinner off > "$TMP/audit.json" 2>"$TMP/audit.err"; AUDIT_RC=$?
cd "$ROOT" || exit 1

"$PY" - "$TMP" "$OUT" "$COVERAGE_MIN" "$PYTEST_RC" "$RUFF_RC" "$BANDIT_RC" "$AUDIT_RC" <<'EOF'
import json, subprocess, sys, xml.etree.ElementTree as ET
from collections import Counter
from datetime import datetime
from pathlib import Path

tmp, out, cov_min = Path(sys.argv[1]), Path(sys.argv[2]), float(sys.argv[3])
pytest_rc, ruff_rc, bandit_rc, audit_rc = map(int, sys.argv[4:8])

def load(name, default):
    try:
        return json.loads((tmp / name).read_text() or 'null') or default
    except (OSError, ValueError):
        return default

suite = ET.parse(tmp / 'junit.xml').getroot()
suite = suite if suite.tag == 'testsuite' else suite.find('testsuite')
tests, failures, errors, skipped = (int(suite.get(k, 0)) for k in ('tests', 'failures', 'errors', 'skipped'))
duration = float(suite.get('time', 0))

cov = load('coverage.json', {})
totals = cov.get('totals', {})
line_pct = totals.get('percent_covered', 0.0)
branch_pct = 100 * totals.get('covered_branches', 0) / max(totals.get('num_branches', 1), 1)
lowest = sorted(((f['summary']['percent_covered'], name, f['missing_lines'])
                 for name, f in cov.get('files', {}).items() if f['summary']['num_statements'] >= 5))[:5]

ruff = load('ruff.json', [])
ruff_by_rule = Counter(item['code'] for item in ruff)

bandit = load('bandit.json', {})
issues = bandit.get('results', [])
by_sev = Counter(i['issue_severity'] for i in issues)
skipped_nosec = bandit.get('metrics', {}).get('_totals', {}).get('skipped_tests', 0)
loc = bandit.get('metrics', {}).get('_totals', {}).get('loc', 0)

audit = load('audit.json', {})
deps = audit.get('dependencies', [])
vulns = [(d['name'], d['version'], v['id'], ', '.join(v.get('fix_versions', [])) or '-')
         for d in deps for v in d.get('vulns', [])]

commit = subprocess.run(['git', 'rev-parse', '--short', 'HEAD'], capture_output=True, text=True).stdout.strip()
ok = lambda cond: '✅ pass' if cond else '❌ fail'
rows = [
    ('Tests (pytest, unit + integration)', f'{tests - failures - errors - skipped}/{tests} passed in {duration:.0f}s',
     'all pass', ok(pytest_rc == 0 and failures + errors == 0)),
    ('Line coverage', f'{line_pct:.2f} %', f'≥ {cov_min:.0f} %', ok(line_pct >= cov_min)),
    ('Branch coverage', f'{branch_pct:.2f} %', 'informative', '—'),
    ('Lint (ruff: E, F, W, B)', f'{len(ruff)} findings', '0', ok(ruff_rc == 0 and not ruff)),
    ('Code security (bandit)', f"high {by_sev['HIGH']} · medium {by_sev['MEDIUM']} · low {by_sev['LOW']}",
     '0 high/medium', ok(bandit_rc == 0)),
    ('Vulnerable dependencies (pip-audit)', f'{len(vulns)} known vulnerabilities in {len(deps)} packages',
     '0', ok(audit_rc == 0 and not vulns)),
]

md = [f'# Quality report — MecaTrack', '',
      f'Generated by `scripts/quality_report.sh` on {datetime.now().astimezone():%Y-%m-%d %H:%M %Z} '
      f'(commit `{commit}`). Same tools and gates as the `test` stage of the CI/CD pipeline.', '',
      '| Metric | Value | Gate | Status |', '|---|---|---|---|']
md += [f'| {a} | {b} | {c} | {d} |' for a, b, c, d in rows]
md += ['', '## Coverage — lowest files (≥ 5 statements)', '', '| File | Coverage | Missing lines |', '|---|---:|---|']
md += [f'| `{name}` | {pct:.1f} % | {", ".join(map(str, missing[:12]))}{" …" if len(missing) > 12 else ""} |'
       for pct, name, missing in lowest]
md += ['', '## Lint', '', 'No findings.' if not ruff else
       ', '.join(f'`{rule}` × {n}' for rule, n in ruff_by_rule.most_common())]
md += ['', '## Code security (bandit)', '',
       f'{loc} lines scanned; {skipped_nosec} findings suppressed with a justified `# nosec` '
       '(constant DuckDB SQL, retry jitter). Remaining findings:', '',
       '| Severity | Test | Location | Note |', '|---|---|---|---|']
md += [f"| {i['issue_severity'].lower()} | {i['test_id']} | `{i['filename'].lstrip('./')}:{i['line_number']}` | "
       f"{i['issue_text']} |" for i in sorted(issues, key=lambda i: (i['issue_severity'], i['filename']))]
if issues and all(i['test_id'] == 'B105' for i in issues):
    md += ['', 'All remaining findings are low-severity B105 false positives: the literal `Bearer`, the test-only '
           'configuration and OpenAPI examples (review recorded in `docs/AI_USAGE_LOG.md`, Phase 4).']
md += ['', '## Dependencies (pip-audit)', '',
       f'{len(deps)} packages from `backend/requirements.txt` checked against the PyPI advisory database: '
       + ('no known vulnerabilities.' if not vulns else f'{len(vulns)} vulnerabilities.')]
if vulns:
    md += ['', '| Package | Version | Advisory | Fixed in |', '|---|---|---|---|']
    md += [f'| {a} | {b} | {c} | {d} |' for a, b, c, d in vulns]
out.write_text('\n'.join(md) + '\n', encoding='utf-8')

width = max(len(r[0]) for r in rows)
print('\nMecaTrack quality summary (commit %s)' % commit)
for a, b, c, d in rows:
    print(f'  {a:<{width}}  {b:<45} gate: {c:<14} {d}')
print(f'\nReport written to {out.relative_to(Path.cwd())}')
sys.exit(0 if all('fail' not in r[3] for r in rows) else 1)
EOF
